#!/usr/bin/env python3
"""Win+P style display cycle helper for Noctalia Suite under Umbriel."""

import fcntl
import glob
import json
import os
import re
import subprocess
import sys
import tempfile
import tomllib


HEADER = """# Generated by Noctalia display-cycle and umbriel-displays. Rewritten on every change.
# Included from config.toml, which must not declare [output.*] of its own:
# values in an including file override every include.
"""


def is_lid_closed(lid_glob: str = "/proc/acpi/button/lid/*/state") -> bool:
    for path in glob.glob(lid_glob):
        try:
            with open(path, "r", encoding="utf-8") as f:
                if "closed" in f.read().lower():
                    return True
        except Exception:
            pass
    return False


def _primary_drm_card(wlr_drm_devices: str | None = None) -> str:
    if wlr_drm_devices is None:
        wlr_drm_devices = os.environ.get("WLR_DRM_DEVICES", "")
    first_entry = next((part.strip() for part in wlr_drm_devices.split(":") if part.strip()), "")
    return os.path.basename(first_entry) if first_entry else ""


def _connected_cards_for_output(output_name: str, drm_sysfs: str = "/sys/class/drm") -> list[str]:
    cards: list[str] = []
    if not output_name:
        return cards
    pattern = os.path.join(drm_sysfs, f"card*-{output_name}", "status")
    for status_path in sorted(glob.glob(pattern)):
        try:
            with open(status_path, "r", encoding="utf-8") as f:
                if f.read().strip() == "connected":
                    conn_dir = os.path.basename(os.path.dirname(status_path))
                    cards.append(conn_dir.split("-", 1)[0])
        except Exception:
            pass
    return cards


def is_output_on_secondary_gpu(
    output_name: str,
    drm_sysfs: str = "/sys/class/drm",
    wlr_drm_devices: str | None = None,
) -> bool:
    primary_card = _primary_drm_card(wlr_drm_devices)
    if not primary_card or not output_name:
        return False
    connected_cards = _connected_cards_for_output(output_name, drm_sysfs=drm_sysfs)
    return bool(connected_cards) and primary_card not in connected_cards


def is_internal_on_secondary_gpu(
    internal_name: str,
    drm_sysfs: str = "/sys/class/drm",
    wlr_drm_devices: str | None = None,
) -> bool:
    return is_output_on_secondary_gpu(internal_name, drm_sysfs=drm_sysfs, wlr_drm_devices=wlr_drm_devices)


def secondary_external_vendor(
    external_names: list[str],
    drm_sysfs: str = "/sys/class/drm",
    wlr_drm_devices: str | None = None,
) -> str:
    primary_card = _primary_drm_card(wlr_drm_devices)
    if not primary_card:
        return ""
    vendor_names = {"nvidia": "NVIDIA", "amdgpu": "AMD", "i915": "Intel", "xe": "Intel"}
    for name in external_names:
        for card in _connected_cards_for_output(name, drm_sysfs=drm_sysfs):
            if card != primary_card:
                uevent_path = os.path.join(drm_sysfs, card, "device", "uevent")
                try:
                    with open(uevent_path, "r", encoding="utf-8") as f:
                        for line in f:
                            if line.startswith("DRIVER="):
                                drv = line.split("=", 1)[1].strip().lower()
                                return vendor_names.get(drv, "external")
                except Exception:
                    pass
                return "external"
    return ""


def get_next_mode_path() -> str:
    state_home = os.environ.get("XDG_STATE_HOME", os.path.expanduser("~/.local/state"))
    return os.path.join(state_home, "noctalia-suite", "next-display-mode")


def read_staged_mode(path: str) -> str:
    if not path or not os.path.exists(path):
        return ""
    try:
        with open(path, "r", encoding="utf-8") as f:
            val = f.read().strip().lower()
            return "laptop" if val == "internal" else val
    except Exception:
        return ""


def write_staged_mode(path: str, mode: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with tempfile.NamedTemporaryFile("w", dir=os.path.dirname(path), suffix=".tmp", delete=False) as f:
        f.write(f"{mode}\n")
        tmp_name = f.name
    os.replace(tmp_name, path)


def clear_staged_mode(path: str) -> None:
    try:
        if path and os.path.exists(path):
            os.remove(path)
    except Exception:
        pass


def _notify(summary: str, body: str = "") -> None:
    cmd = ["notify-send", "-a", "Displays", "-i", "video-display", summary]
    if body:
        cmd.append(body)
    subprocess.run(cmd, check=False)


def get_outputs() -> list[dict]:
    try:
        res = subprocess.run(["umbriel", "outputs", "--json"], capture_output=True, text=True, check=True)
        return json.loads(res.stdout)
    except Exception as e:
        print(f"display-cycle: failed to query umbriel outputs: {e}", file=sys.stderr)
        return []


def handle_ddc_input(outputs: list[dict], target_vcp: str = "0x0f") -> None:
    focused = next((o.get("name") for o in outputs if o.get("focused")), None)
    if not focused:
        focused = outputs[0].get("name") if outputs else None
    if not focused:
        return

    try:
        detect = subprocess.run(["ddcutil", "detect", "--terse"], capture_output=True, text=True)
        bus = None
        for block in detect.stdout.split("\n\n"):
            if f"-{focused}" in block:
                m = re.search(r"I2C bus:\s+/dev/i2c-(\d+)", block)
                if m:
                    bus = m.group(1)
                    break
        if bus:
            subprocess.run(["ddcutil", "--bus", bus, "setvcp", "60", target_vcp], check=False)
    except Exception as e:
        print(f"display-cycle: ddcutil input switch failed: {e}", file=sys.stderr)


def read_outputs_toml(path: str) -> dict[str, dict]:
    if not os.path.exists(path):
        return {}
    try:
        with open(path, "rb") as f:
            data = tomllib.load(f)
            return data.get("output", {})
    except Exception:
        return {}


def format_value(val) -> str:
    if isinstance(val, bool):
        return "true" if val else "false"
    if isinstance(val, (int, float)):
        return str(val)
    if isinstance(val, list):
        return "[" + ", ".join(format_value(v) for v in val) + "]"
    return json.dumps(str(val))


def render_outputs_toml(sections: dict[str, dict]) -> str:
    lines = [HEADER.rstrip()]
    for key, fields in sorted(sections.items()):
        lines.append("")
        lines.append(f'[output."{key}"]')
        priority_keys = ["position", "scale", "mode", "enabled", "transform"]
        written = set()
        for k in priority_keys:
            if k in fields:
                lines.append(f"{k} = {format_value(fields[k])}")
                written.add(k)
        for k, v in sorted(fields.items()):
            if k not in written:
                lines.append(f"{k} = {format_value(v)}")
    lines.append("")
    return "\n".join(lines)


def get_identity_key(output: dict, all_outputs: list[dict]) -> str:
    cfg = output.get("config_name", "")
    name = output.get("name", "")
    if not cfg:
        return name
    if sum(1 for o in all_outputs if o.get("config_name", "") == cfg) > 1:
        return name
    return cfg


def get_default_scale(output: dict) -> float:
    modes = output.get("modes", [])
    max_w = max((m.get("width", 0) for m in modes), default=0)
    if max_w >= 3840:
        return 1.25
    return 1.0


def get_logical_height(output: dict, scale: float) -> int:
    modes = output.get("modes", [])
    pref = next((m for m in modes if m.get("preferred")), modes[0] if modes else {})
    h = pref.get("height", 1080)
    return int(round(h / scale))


def calculate_next_state(
    outputs: list[dict],
    lid_closed: bool,
    existing_sections: dict[str, dict],
    requested_mode: str = "",
    internal_on_secondary_gpu: bool = False,
    staged_mode: str = "",
) -> tuple[str, dict[str, dict], str]:
    """Calculate the action, new sections dict, and user-facing message."""
    if not outputs:
        return "none", {}, ""

    internal = next((o for o in outputs if re.match(r"^(eDP|LVDS|DSI)-", o.get("name", ""))), None)
    externals = [o for o in outputs if not re.match(r"^(eDP|LVDS|DSI)-", o.get("name", ""))]

    if requested_mode == "input":
        return "input", {}, ""

    if not internal or not externals:
        if internal and not externals and not lid_closed:
            internal_key = get_identity_key(internal, outputs)
            if not bool(internal.get("enabled", False)) or existing_sections.get(internal_key, {}).get("enabled") is False:
                new_sections = {k: dict(v) for k, v in existing_sections.items()}
                internal_sec = new_sections.setdefault(internal_key, {})
                internal_sec.pop("enabled", None)
                internal_sec["scale"] = internal_sec.get("scale", internal.get("scale") or get_default_scale(internal))
                internal_sec["position"] = [0, 0]
                return "apply", new_sections, "Built-in display"
        if requested_mode == "relayout":
            return "none", {}, ""
        return "toggle_panel", {}, ""

    internal_on = bool(internal.get("enabled", False))
    external_on = any(bool(o.get("enabled", False)) for o in externals)

    forced_message: str | None = None
    if lid_closed:
        if internal_on or not external_on:
            target_mode = "external"
            forced_message = "External display only (Laptop lid is closed)"
        elif requested_mode == "relayout":
            return "none", {}, ""
        else:
            return "lid_closed_warning", {}, "External display only (Laptop lid is closed)"
    elif internal_on_secondary_gpu:
        if internal_on or not external_on:
            target_mode = "external"
            forced_message = "External display only (Re-login with lid open to use built-in display)"
        elif requested_mode == "relayout":
            return "none", {}, ""
        elif requested_mode == "external":
            if staged_mode:
                return "unstage_intel", {}, "Staying on External display only"
            return "gpu_locked_warning", {}, "External display only (Re-login with lid open to use built-in display)"
        else:
            if staged_mode and requested_mode == "":
                return "unstage_intel", {}, "Staying on External display only"
            staged_target = "laptop" if requested_mode in ("laptop", "internal") else "extend"
            return "stage_intel", {}, staged_target
    else:
        if internal_on and external_on:
            current_mode = "extend"
        elif external_on and not internal_on:
            current_mode = "external"
        elif internal_on and not external_on:
            current_mode = "laptop"
        else:
            current_mode = "unknown"

        if requested_mode == "relayout":
            if staged_mode in ("extend", "laptop"):
                target_mode = staged_mode
            elif not internal_on and not external_on:
                target_mode = "extend"
            else:
                return "none", {}, ""
        elif requested_mode in ("external", "laptop", "internal", "extend"):
            target_mode = "laptop" if requested_mode == "internal" else requested_mode
        else:
            if current_mode == "external":
                target_mode = "laptop"
            elif current_mode == "laptop":
                target_mode = "extend"
            elif current_mode == "extend":
                target_mode = "external"
            else:
                target_mode = "extend"

    new_sections: dict[str, dict] = {}
    for k, v in existing_sections.items():
        new_sections[k] = dict(v)

    internal_key = get_identity_key(internal, outputs)
    internal_sec = new_sections.setdefault(internal_key, {})

    for o in externals:
        k = get_identity_key(o, outputs)
        sec = new_sections.setdefault(k, {})
        sec.pop("enabled", None)

    internal_sec.pop("enabled", None)

    if target_mode == "external":
        internal_sec["enabled"] = False
        for o in externals:
            k = get_identity_key(o, outputs)
            sec = new_sections[k]
            scale = sec.get("scale", o.get("scale") or get_default_scale(o))
            sec["scale"] = scale
            sec["position"] = [0, 0]
        mode_title = forced_message or "External displays"

    elif target_mode == "laptop":
        for o in externals:
            k = get_identity_key(o, outputs)
            new_sections[k]["enabled"] = False
        scale = internal_sec.get("scale", internal.get("scale") or get_default_scale(internal))
        internal_sec["scale"] = scale
        internal_sec["position"] = [0, 0]
        mode_title = "Laptop display"

    elif target_mode == "extend":
        primary_ext = externals[0]
        primary_key = get_identity_key(primary_ext, outputs)
        ext_sec = new_sections[primary_key]
        ext_scale = ext_sec.get("scale", primary_ext.get("scale") or get_default_scale(primary_ext))
        ext_sec["scale"] = ext_scale
        ext_sec["position"] = [0, 0]

        ext_height = get_logical_height(primary_ext, ext_scale)

        int_scale = internal_sec.get("scale", internal.get("scale") or get_default_scale(internal))
        internal_sec["scale"] = int_scale
        internal_sec["position"] = [0, ext_height]

        # Additional externals laid out to the right
        current_x = int(round((primary_ext.get("modes", [{}])[0].get("width", 3840)) / ext_scale))
        for extra_ext in externals[1:]:
            k = get_identity_key(extra_ext, outputs)
            sec = new_sections[k]
            scale = sec.get("scale", extra_ext.get("scale") or get_default_scale(extra_ext))
            sec["scale"] = scale
            sec["position"] = [current_x, 0]
            w = extra_ext.get("modes", [{}])[0].get("width", 1920)
            current_x += int(round(w / scale))

        mode_title = "Extend displays"
    else:
        return "none", {}, ""

    return "apply", new_sections, mode_title


def acquire_lock():
    runtime_dir = os.environ.get("XDG_RUNTIME_DIR", tempfile.gettempdir())
    lock_path = os.path.join(runtime_dir, "display-cycle.lock")
    try:
        lock_file = open(lock_path, "w")
        fcntl.flock(lock_file.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        return lock_file
    except (BlockingIOError, OSError):
        return None


def main() -> None:
    lock = acquire_lock()
    if lock is None:
        sys.exit(0)

    arg = sys.argv[1] if len(sys.argv) > 1 else ""

    outputs = get_outputs()
    lid_closed = is_lid_closed()
    internal = next((o for o in outputs if re.match(r"^(eDP|LVDS|DSI)-", o.get("name", ""))), None)
    externals = [o.get("name", "") for o in outputs if not re.match(r"^(eDP|LVDS|DSI)-", o.get("name", ""))]
    internal_secondary = is_internal_on_secondary_gpu(internal["name"]) if internal else False

    config_home = os.environ.get("XDG_CONFIG_HOME", os.path.expanduser("~/.config"))
    outputs_path = os.path.join(config_home, "umbriel", "outputs.toml")
    existing_sections = read_outputs_toml(outputs_path)
    next_mode_path = get_next_mode_path()
    staged_mode = read_staged_mode(next_mode_path)

    action, new_sections, message = calculate_next_state(
        outputs,
        lid_closed,
        existing_sections,
        requested_mode=arg,
        internal_on_secondary_gpu=internal_secondary,
        staged_mode=staged_mode,
    )

    if action == "input":
        target_vcp = sys.argv[2] if len(sys.argv) > 2 else "0x0f"
        handle_ddc_input(outputs, target_vcp)
        sys.exit(0)

    if action == "toggle_panel":
        subprocess.run(["noctalia", "msg", "panel-toggle", "control-center", "monitor"], check=False)
        sys.exit(0)

    if action == "lid_closed_warning":
        _notify("External display only", "Laptop lid is closed")
        sys.exit(0)

    if action == "gpu_locked_warning":
        _notify("External display only", "Re-login with lid open to use built-in display")
        sys.exit(0)

    if action == "stage_intel":
        write_staged_mode(next_mode_path, message)
        label = "Laptop display" if message == "laptop" else "Extend displays"
        _notify(
            f"Next login: {label} (Intel)",
            "Press Super+Escape to re-login on Intel, or F7 again to cancel",
        )
        sys.exit(0)

    if action == "unstage_intel":
        clear_staged_mode(next_mode_path)
        _notify("Staying on External display only", "Canceled switch to Intel")
        sys.exit(0)

    if action == "none":
        if arg == "relayout":
            clear_staged_mode(next_mode_path)
        sys.exit(0)

    if action == "apply":
        os.makedirs(os.path.dirname(outputs_path), exist_ok=True)
        toml_content = render_outputs_toml(new_sections)

        with tempfile.NamedTemporaryFile("w", dir=os.path.dirname(outputs_path), suffix=".tmp", delete=False) as f:
            f.write(toml_content)
            tmp_name = f.name

        val = subprocess.run(["umbriel", "config", "validate", "-c", tmp_name], capture_output=True, text=True)
        if val.returncode != 0:
            os.remove(tmp_name)
            print(f"display-cycle: validation failed: {val.stderr or val.stdout}", file=sys.stderr)
            sys.exit(1)

        os.replace(tmp_name, outputs_path)
        clear_staged_mode(next_mode_path)
        subprocess.run(["umbriel", "msg", "config-reload"], check=False)
        body = ""
        if message == "External displays":
            vendor = secondary_external_vendor(externals)
            if vendor:
                body = f"Re-login (Super+Escape) for direct {vendor} GPU"
        _notify(message, body)
        sys.exit(0)


if __name__ == "__main__":
    main()
